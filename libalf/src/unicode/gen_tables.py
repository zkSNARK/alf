#!/usr/bin/env python3
"""Generates unicode_tables.h from Python's Unicode database (unicodedata).

    python3 libalf/src/unicode/gen_tables.py > libalf/src/unicode/unicode_tables.h

Word characters: what ripgrep's \\w (Unicode) means: Alphabetic, marks, decimal digits,
connector punctuation and the joiners.  Alphabetic is taken as the letter categories (L*) and
letter numbers (Nl) plus the Other_Alphabetic code points outside the mark categories (circled
and squared Latin letters), which unicodedata doesn't list."""
import sys
import unicodedata

OTHER_ALPHABETIC_SYMBOLS = [(0x24B6, 0x24E9), (0x1F130, 0x1F149), (0x1F150, 0x1F169), (0x1F170, 0x1F189)]
JOIN_CONTROL = [(0x200C, 0x200D)]


def is_word(cp):
    c = unicodedata.category(chr(cp))
    if c[0] in "LM" or c in ("Nd", "Nl", "Pc"):
        return True
    return any(lo <= cp <= hi for lo, hi in OTHER_ALPHABETIC_SYMBOLS + JOIN_CONTROL)


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:  # surrogates: never in valid UTF-8
            ok = False
        else:
            ok = pred(cp)
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def main():
    w = ranges(is_word)
    print("// Generated by gen_tables.py from Unicode %s (Python %s). Do not edit." % (unicodedata.unidata_version, sys.version.split()[0]))
    print("#pragma once")
    print()
    print("namespace alf::unicode")
    print("{")
    print("  struct Range")
    print("  {")
    print("    char32_t lo, hi;")
    print("  };")
    print()
    print("  // Word characters (as ripgrep's \\w), sorted, disjoint: %d ranges." % len(w))
    print("  inline constexpr Range word_ranges[] = {")
    for i in range(0, len(w), 4):
        print("    " + " ".join("{ 0x%X, 0x%X }," % r for r in w[i:i + 4]))
    print("  };")
    print("}")


main()
