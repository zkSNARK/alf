#!/usr/bin/env python3
"""Generates unicode_tables.h from Python's Unicode database (unicodedata).

Case folding: Unicode's simple case folding (one code point to one code point, as ripgrep's -i
uses), taken from Python as: str.casefold() where that gives a single code point, otherwise
str.lower() where that does (so ß stays ß, as in simple folding, while ſ folds to s and the
Kelvin sign to k).

    python3 libalf/src/unicode/gen_tables.py > libalf/src/unicode/unicode_tables.h

Word characters: what ripgrep's \\w (Unicode) means: Alphabetic, marks, decimal digits,
connector punctuation and the joiners.  Alphabetic is taken as the letter categories (L*) and
letter numbers (Nl) plus the Other_Alphabetic code points outside the mark categories (circled
and squared Latin letters), which unicodedata doesn't list."""
import sys
import unicodedata

OTHER_ALPHABETIC_SYMBOLS = [(0x24B6, 0x24E9), (0x1F130, 0x1F149), (0x1F150, 0x1F169), (0x1F170, 0x1F189)]
JOIN_CONTROL = [(0x200C, 0x200D)]


def is_word(cp):
    c = unicodedata.category(chr(cp))
    if c[0] in "LM" or c in ("Nd", "Nl", "Pc"):
        return True
    return any(lo <= cp <= hi for lo, hi in OTHER_ALPHABETIC_SYMBOLS + JOIN_CONTROL)


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:  # surrogates: never in valid UTF-8
            ok = False
        else:
            ok = pred(cp)
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def simple_fold(cp):
    if 0xD800 <= cp <= 0xDFFF:
        return cp
    ch = chr(cp)
    for f in (ch.casefold(), ch.lower()):
        if len(f) == 1:
            return ord(f)
    return cp


def main():
    w = ranges(is_word)
    fold = [(cp, simple_fold(cp)) for cp in range(0x110000) if simple_fold(cp) != cp]
    members = {}
    for cp, f in fold:
        members.setdefault(f, {f}).add(cp)
    orbit = sorted((f, m) for f, ms in members.items() for m in ms)
    print("// Generated by gen_tables.py from Unicode %s (Python %s). Do not edit." % (unicodedata.unidata_version, sys.version.split()[0]))
    print("#pragma once")
    print()
    print("namespace alf::unicode")
    print("{")
    print("  struct Range")
    print("  {")
    print("    char32_t lo, hi;")
    print("  };")
    print()
    print("  // Word characters (as ripgrep's \\w), sorted, disjoint: %d ranges." % len(w))
    print("  inline constexpr Range word_ranges[] = {")
    for i in range(0, len(w), 4):
        print("    " + " ".join("{ 0x%X, 0x%X }," % r for r in w[i:i + 4]))
    print("  };")
    print()
    print("  struct Fold")
    print("  {")
    print("    char32_t from, to;")
    print("  };")
    print()
    print("  // Simple case folding, sorted by `from`: every code point not listed folds to itself (%d entries)." % len(fold))
    print("  inline constexpr Fold fold_table[] = {")
    for i in range(0, len(fold), 4):
        print("    " + " ".join("{ 0x%X, 0x%X }," % r for r in fold[i:i + 4]))
    print("  };")
    print()
    print("  // Every code point that folds to `from` (including itself), sorted by `from`, then `to` (%d entries)." % len(orbit))
    print("  inline constexpr Fold orbit_table[] = {")
    for i in range(0, len(orbit), 4):
        print("    " + " ".join("{ 0x%X, 0x%X }," % r for r in orbit[i:i + 4]))
    print("  };")
    print("}")


main()
